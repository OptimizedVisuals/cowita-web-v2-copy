/**
 * CoWiTa — self-host the site fonts.
 *
 * Fetches the Google Fonts CSS for DM Sans and Lora (latin + latin-ext), saves
 * the .woff2 files under /assets/fonts, and writes /css/fonts.css with local
 * @font-face rules. Self-hosting removes a third-party dependency from the
 * critical path, lets the strict CSP use font-src 'self', and avoids sending
 * visitor IPs to Google.
 *
 * Run with:  node tools/selfhost-fonts.mjs
 * (Network access required. Re-run only when the font list changes.)
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const fontDir = join(root, 'assets', 'fonts');
const cssPath = join(root, 'css', 'fonts.css');

// Inter is the body font named in --font-sans; Lora is the display font.
// (The old Google Fonts tag asked for DM Sans, which no stylesheet used.)
const GOOGLE_CSS =
  'https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=Lora:wght@400;500;600&display=swap';

const BROWSER_UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

const KEEP_SUBSETS = new Set(['latin', 'latin-ext']);

const SLUGS = {
  Inter: 'inter',
  Lora: 'lora',
};

mkdirSync(fontDir, { recursive: true });

const css = await fetch(GOOGLE_CSS, { headers: { 'User-Agent': BROWSER_UA } }).then((res) => {
  if (!res.ok) throw new Error(`Font CSS request failed: ${res.status}`);
  return res.text();
});

/** @type {{ comment: string, block: string }[]} */
const entries = [];
const pattern = /\/\*\s*([a-z0-9-]+)\s*\*\/\s*(@font-face\s*\{[\s\S]*?\})/gi;
let match;

while ((match = pattern.exec(css)) !== null) {
  entries.push({ subset: match[1], block: match[2] });
}

if (!entries.length) {
  throw new Error('Could not parse any @font-face blocks from the Google Fonts response.');
}

const output = [
  '/* =========================================================',
  '   CoWiTa fonts — self-hosted',
  '   Generated by tools/selfhost-fonts.mjs. Do not edit by hand.',
  '   Inter (body) and Lora (display), latin + latin-ext only.',
  '   font-display: swap keeps text visible while fonts load.',
  '========================================================= */',
  '',
];

let downloaded = 0;

for (const entry of entries) {
  if (!KEEP_SUBSETS.has(entry.subset)) continue;

  const urlMatch = entry.block.match(/url\((https:\/\/fonts\.gstatic\.com[^)]+\.woff2)\)/i);
  const familyMatch = entry.block.match(/font-family:\s*['"]?([^'";]+)['"]?/i);
  const weightMatch = entry.block.match(/font-weight:\s*(\d+)/i);
  const styleMatch = entry.block.match(/font-style:\s*([a-z]+)/i);
  const rangeMatch = entry.block.match(/unicode-range:\s*([^;]+);/i);

  if (!urlMatch || !familyMatch) continue;

  const family = familyMatch[1].trim();
  const slug = SLUGS[family] || family.toLowerCase().replace(/\s+/g, '-');
  const weight = weightMatch ? weightMatch[1] : '400';
  const style = styleMatch ? styleMatch[1] : 'normal';
  const fileName = `${slug}-${weight}-${style}-${entry.subset}.woff2`;

  const response = await fetch(urlMatch[1], { headers: { 'User-Agent': BROWSER_UA } });

  if (!response.ok) {
    console.warn(`skipped ${fileName}: ${response.status}`);
    continue;
  }

  const buffer = Buffer.from(await response.arrayBuffer());
  writeFileSync(join(fontDir, fileName), buffer);
  downloaded += 1;

  output.push('@font-face {');
  output.push(`  font-family: '${family}';`);
  output.push(`  font-style: ${style};`);
  output.push(`  font-weight: ${weight};`);
  output.push("  font-display: swap;");
  output.push(`  src: url('/assets/fonts/${fileName}') format('woff2');`);
  if (rangeMatch) output.push(`  unicode-range: ${rangeMatch[1].trim()};`);
  output.push('}');
  output.push('');
}

writeFileSync(cssPath, `${output.join('\n')}\n`, 'utf8');

console.log(`${downloaded} font file(s) written to assets/fonts/`);
console.log('css/fonts.css regenerated');
